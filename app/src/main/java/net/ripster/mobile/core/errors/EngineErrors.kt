package net.ripster.mobile.core.errors

/**
 * Маркеры ошибок движков — вместо готового текста на одном языке.
 *
 * Движок живёт в core-слое и языка интерфейса не знает: до этой правки он
 * бросал `IOException("Beatport: не удалось авторизоваться…")`, и очередь
 * загрузок печатала это как есть — англоязычный тестер видел русскую строку.
 * Теперь движок бросает маркер, а переводит его экран
 * ([net.ripster.mobile.ui.i18n.engineErrorText]) уже на языке пользователя.
 *
 * Формат — `__e.<ключ>__` плюс необязательный хвост через пробел: код ответа,
 * секунды паузы, сообщение чужой стороны. Хвост не переводится и добавляется в
 * скобках — детали нужны для разбора, но текст без них уже осмысленный.
 *
 * Классы различаем по тому, что человеку делать дальше: «обнови ключи» и
 * «истёк токен» ведут в разные места настроек, поэтому это разные ключи, а не
 * один «ошибка авторизации». Пять состояний ПК-моста тоже разные: «не сопряжён»
 * чинится сопряжением, «нет связи» — сетью, «ПК отклонил» — уже на стороне ПК.
 *
 * Ключ здесь = ключ `err.<...>` в таблице строк; добавляя маркер, добавляй и
 * перевод на все пять языков, иначе на экране будет виден сам ключ.
 */
object EngineErrors {

    /** Регион: BBC отдаёт эфир только из Великобритании. */
    const val GEO_UK = "__e.geo_uk__"

    /** Логин/пароль/подписка сервиса не дали авторизоваться. */
    const val AUTH_FAILED = "__e.auth_failed__"

    /** Токен есть, но сервис его не принял — нужен повторный вход. */
    const val TOKEN_INVALID = "__e.token_invalid__"

    /** Qobuz: не выходит добыть app_id/app_secret автоматически. */
    const val QOBUZ_KEYS = "__e.qobuz_keys__"

    /** Ответ/поток пустой там, где ожидались данные. */
    const val EMPTY_STREAM = "__e.empty_stream__"

    /** Лимит запросов, сервис попросил подождать. Хвост — секунды. */
    const val RATE_LIMITED = "__e.rate_limited__"

    /** Поток под DRM — вне области скачивания. */
    const val DRM_UNSUPPORTED = "__e.drm_unsupported__"

    /** Прочий отказ по HTTP. Хвост — код и endpoint. */
    const val HTTP = "__e.http__"

    /** Совпадение не найдено (конверсия Spotify). */
    const val NOT_FOUND = "__e.not_found__"

    /** Трек у сервиса больше не отдаётся — снят, перезалит, скрыт. */
    const val TRACK_UNAVAILABLE = "__e.track_unavailable__"

    /** Файл есть, но не для этой учётки или страны. */
    const val NO_SOURCE_REGION = "__e.no_source_region__"

    /** Срок доступа вышел либо запись закрыта по региону — BBC не различает. */
    const val EXPIRED_OR_GEO = "__e.expired_or_geo__"

    /** Сервис отдаёт трек только сегментами — играть нечего, скачать можно. */
    const val NO_DIRECT_STREAM = "__e.no_direct_stream__"

    /** У передачи нет звуковой дорожки для скачивания. */
    const val NO_AUDIO = "__e.no_audio__"

    // --- Apple: скачивание идёт через сопряжённый ПК ---

    /** Прямого потока у Apple на телефоне нет — только через ПК. */
    const val PC_ONLY = "__e.pc_only__"

    /** В задаче нет ссылки, скачивать нечего. */
    const val NO_LINK = "__e.no_link__"

    /** ПК не сопряжён или не умеет Apple Music. */
    const val PC_UNPAIRED = "__e.pc_unpaired__"

    /** ПК принял запрос и отказал. Хвост — его причина. */
    const val PC_REJECTED = "__e.pc_rejected__"

    /** ПК взял задачу, но не довёл до конца. Хвост — его причина. */
    const val PC_INCOMPLETE = "__e.pc_incomplete__"

    /** Связь с ПК пропала. Хвост — сетевая причина. */
    const val PC_OFFLINE = "__e.pc_offline__"

    /** Файл на ПК готов, но забрать не удалось. Хвост — причина. */
    const val PC_FETCH_FAILED = "__e.pc_fetch_failed__"

    /** Маркер с хвостом-деталью: `code(HTTP, "503")` → `"__e.http__ 503"`. */
    fun code(marker: String, detail: String?): String =
        if (detail.isNullOrBlank()) marker else "$marker $detail"
}
