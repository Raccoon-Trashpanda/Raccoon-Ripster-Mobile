package net.ripster.mobile.core.download

/**
 * Отличить «сейчас не вышло» от «не выйдет никогда».
 *
 * 05.09.2026: «Скачать альбом» на девятнадцать треков дало тринадцать красных
 * строк «Apple: 429 Too Many Requests». Ошибка честная — девятнадцать задач
 * подряд дёргают у сервиса один и тот же альбом, и он просит подождать. Но
 * записывалась она как окончательный отказ: человек видел тринадцать
 * «не скачалось» там, где надо было просто выждать полминуты.
 *
 * Ограничение частоты, обрыв связи и «сервер прилёг» — это НЕ приговор треку.
 * У воркера уже настроен экспоненциальный откат, оставалось им воспользоваться.
 *
 * Осторожность в обе стороны. Считать временным то, что временным не является,
 * — значит крутить безнадёжную задачу по кругу и прятать настоящую причину
 * («нет подписки», «регион», «трека нет»). Поэтому список закрытый и короткий:
 * только то, что заведомо проходит само.
 */
object TransientFailure {

    private val MARKERS = listOf(
        "429", "too many requests", "rate limit",
        "502", "503", "504", "bad gateway", "service unavailable", "gateway timeout",
        "timeout", "timed out",
        "connection reset", "connection abort", "connection refused",
        "unexpected end of stream", "software caused connection",
    )

    /** Максимум повторов, после которого причина показывается человеку как есть. */
    const val MAX_ATTEMPTS = 4

    fun isTransient(reason: String?): Boolean {
        val s = reason?.lowercase() ?: return false
        // «404», «нет подписки», «регион» и прочее окончательное сюда не
        // попадает по умолчанию: не знаем — значит не временное. Ошибиться
        // здесь в сторону «повторим» дороже: настоящая причина спрячется.
        return MARKERS.any { it in s }
    }

    /** Стоит ли пробовать ещё раз: причина временная И попытки не исчерпаны. */
    fun shouldRetry(reason: String?, attempt: Int): Boolean =
        isTransient(reason) && attempt < MAX_ATTEMPTS
}
