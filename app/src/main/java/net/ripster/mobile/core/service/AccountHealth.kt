package net.ripster.mobile.core.service

/**
 * Что учётка сервиса РЕАЛЬНО может — измеренное, а не заявленное.
 *
 * Появилось 12.09.2026 по просьбе владельца сделать на телефоне то же, что на
 * ПК: там сторож меряет каждую учётку и сам заменяет основную, если она не
 * отдаёт lossless. До этого телефон знал про учётку ровно одно — есть ли
 * строка токена, — и «подключён» означало «поле заполнено», а не «работает».
 *
 * Три состояния, и третье обязательно:
 *
 * * [alive] = true — сервис ответил и учётку принял;
 * * [alive] = false — сервис ответил и учётку ОТВЕРГ;
 * * [alive] = null — спросить не удалось (сеть, геоблок, сервис лежит).
 *
 * Без третьего состояния упавшая на сутки сеть пометила бы живые учётки
 * мёртвыми — ровно та ошибка, которую на ПК ловили дважды.
 */
data class AccountHealth(
    val alive: Boolean?,
    /** Подписка отдаёт lossless (FLAC/hi-res). false у бесплатных тарифов. */
    val lossless: Boolean = false,
    /** Название тарифа словами сервиса: PREMIUM, INTRO, Plus… Пусто — не сказал. */
    val plan: String = "",
    /** Максимальное качество словами сервиса: HI_RES, LOSSLESS, LOW… */
    val quality: String = "",
    /** Страна учётки: она решает, какие релизы видны и когда. */
    val country: String = "",
    /** Дата окончания подписки, как её отдал сервис. Пусто — не сказал. */
    val validUntil: String = "",
    /** Почему не жива / почему не спросили. Пусто — всё в порядке. */
    val reason: String = "",
    /**
     * Может ли ЭТОТ СЕРВИС вообще отдавать lossless.
     *
     * У SoundCloud его нет ни на каком тарифе, и без этого различия учётка
     * вечно считалась бы «требующей замены»: телефон каждый раз ходил бы к ПК
     * за новыми ключами, которые ничего не изменят.
     */
    val losslessPossible: Boolean = true,
) {
    /** Ничего не спрашивали или спросить не вышло. */
    val unknown: Boolean get() = alive == null

    /** Учёткой можно качать хоть что-то. */
    val usable: Boolean get() = alive == true

    companion object {
        fun unknown(reason: String = ""): AccountHealth = AccountHealth(null, reason = reason)
        fun dead(reason: String): AccountHealth = AccountHealth(false, reason = reason)
    }
}
