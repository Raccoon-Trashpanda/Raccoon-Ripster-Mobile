package net.ripster.mobile.core.service

import kotlin.math.log10
import kotlin.math.min

/**
 * Насколько вещь слушают — приведённое к общей шкале 0..1.
 *
 * Владелец 05.09.2026: «в жанре синтвейв есть куча именитых артистов и групп…
 * нужен механизм определения прослушиваемости, предлагать то, что в жанре
 * действительно популярно». За образец — «Моя волна» Яндекса.
 *
 * Считается ТОЛЬКО из настоящих счётчиков сервиса. Ни релевантность поиска, ни
 * порядок выдачи популярностью не являются: сервис ранжирует под запрос, а не
 * под то, что слушают. Чего сервис не отдал — то `null`, «не знаю»; выдумывать
 * тут особенно вредно, потому что по этому числу вещи потом отбираются.
 *
 * Шкалы разные и несопоставимы напрямую, поэтому каждая приводится к 0..1
 * отдельно и осознанно:
 *
 *  * Deezer отдаёт `rank` 0..1_000_000 — уже готовая доля, делим;
 *  * SoundCloud отдаёт число прослушиваний, а оно растёт на порядки: между
 *    тысячей и десятью тысячами разница та же, что между миллионом и десятью.
 *    Поэтому логарифм: 10 прослушиваний ≈ 0.14, 10 тысяч ≈ 0.57, 10 миллионов
 *    ≈ 1.0. Линейная шкала сделала бы всё, кроме мировых хитов, нулём.
 */
object Popularity {

    /** Верхняя точка логарифмической шкалы: 10^7 прослушиваний = 1.0. */
    private const val PLAYS_TOP = 7.0

    /** Популярность по `rank` Deezer (0..1_000_000). */
    fun fromDeezerRank(rank: Int?): Double? {
        val r = rank ?: return null
        if (r <= 0) return null
        return min(1.0, r / 1_000_000.0)
    }

    /**
     * Популярность по счётчикам SoundCloud. Лайки учитываются как усиление:
     * их на порядки меньше прослушиваний, но именно они отличают то, что
     * действительно слушают, от накрученного.
     */
    fun fromSoundCloudCounts(plays: Long?, likes: Long?): Double? {
        val p = plays ?: return null
        if (p <= 0) return null
        val base = log10(1.0 + p) / PLAYS_TOP
        val boost = likes?.takeIf { it > 0 }?.let { log10(1.0 + it) / (PLAYS_TOP * 4) } ?: 0.0
        return min(1.0, base + boost)
    }
}
