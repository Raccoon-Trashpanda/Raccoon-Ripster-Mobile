package net.ripster.mobile.ui.i18n

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * i18n мобильного приложения. Набор языков — РОВНО как в десктопном Ripster
 * (`static/js/app.js` `_LANG_ORDER = ['ru','en','hi','ja','zh']`), не больше и
 * не меньше. Правило проекта: ни одной user-facing строки хардкодом — новая
 * строка сразу заводится здесь во всех пяти языках.
 *
 * Механика намеренно повторяет десктоп: плоская карта `key -> (lang -> text)`,
 * смена языка в рантайме без пересоздания Activity (через [LocalAppLang]).
 * Ресурсные `strings.xml` не берём — они не дают живого переключения и
 * расходятся с тем, как устроен десктопный контракт.
 *
 * Пока покрыты только строки, которые уже есть на экранах. Экран-витрина и
 * `DownloadsQueueScreen`/прочие демо ещё содержат литералы — их перенос сюда
 * идёт по мере превращения демо в настоящие экраны.
 */
enum class AppLang(val tag: String, val display: String) {
    RU("ru", "Русский"),
    EN("en", "English"),
    HI("hi", "हिन्दी"),
    JA("ja", "日本語"),
    ZH("zh", "中文");

    companion object {
        val ORDER = listOf(RU, EN, HI, JA, ZH)
        fun byTag(tag: String): AppLang = entries.firstOrNull { it.tag == tag } ?: EN
    }
}

/** Текущий язык интерфейса. Дефолт — EN: базовый язык строк, как fallback на десктопе. */
val LocalAppLang = staticCompositionLocalOf { AppLang.EN }

/**
 * Перевод по ключу. Отсутствующий перевод для выбранного языка откатывается на
 * EN, затем на сам ключ (та же семантика, что `t()` на десктопе — ключ на
 * экране виден и сигналит о пропуске).
 */
fun tr(key: String, lang: AppLang): String {
    val row = STRINGS[key] ?: return key
    return row[lang] ?: row[AppLang.EN] ?: key
}

