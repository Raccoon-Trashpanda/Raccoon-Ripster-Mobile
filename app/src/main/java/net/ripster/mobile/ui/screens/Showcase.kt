package net.ripster.mobile.ui.screens

/**
 * Витрина на главном экране: показать РАЗНОЕ, а не всё подряд.
 *
 * Жалоба владельца 05.09.2026: «посмотри что на домашнем экране в самом верху,
 * массив аттак захватил нашу коллекцию подчистую». Так и было: скачали
 * девятнадцать треков одного альбома — и обе полки, «Из вашей коллекции» и
 * «Недавно добавленное», целиком заполнились одной обложкой. Формально всё
 * верно: это и есть коллекция, это и есть недавнее. Но полка, где двенадцать
 * раз подряд одна и та же картинка, выглядит сломанной и ничего не показывает.
 *
 * Отбираем с потолком на артиста, сохраняя ПОРЯДОК, который задал вызывающий
 * (у «недавнего» это свежесть, у «коллекции» — случайная выборка на заход).
 * Если разнообразия не хватает — в фонотеке правда один артист, — добираем
 * остатком: пустая полка хуже однообразной, а врать про чужих артистов
 * нельзя.
 */
object Showcase {

    /** Больше этого числа вещей одного артиста подряд полка не показывает. */
    const val MAX_PER_ARTIST = 2

    private fun norm(s: String): String =
        s.lowercase().substringBefore(",").substringBefore(" feat").trim()

    /**
     * ВСЕ, кто указан в строке артистов, а не только первый.
     *
     * Потолок считал артиста по первому имени — и «Das Kabinett, Massive
     * Attack» проходил как посторонний. На снимке 06.09.2026 полка коллекции
     * из-за этого оказалась целиком в Massive Attack при формально соблюдённом
     * потолке: три обложки, три «разных» артиста, а глазом — один.
     *
     * Полка врала не человеку, а сама себе: она считала то, чего он не видит.
     */
    private fun credited(s: String): List<String> =
        s.split(",", "&", " feat", " x ", " vs ")
            .map { it.trim().lowercase() }
            .filter { it.isNotBlank() }
            .ifEmpty { listOf(norm(s)) }

    /**
     * [take] вещей, не больше [maxPerArtist] от одного артиста.
     *
     * @param artistOf как достать артиста — витрина не знает типа строки.
     * @param avoid ключи вещей, уже стоящих на СОСЕДНЕЙ полке.
     * @param keyOf как достать ключ вещи; нужен только вместе с [avoid].
     */
    fun <T> spread(
        rows: List<T>,
        take: Int,
        maxPerArtist: Int = MAX_PER_ARTIST,
        avoid: Set<String> = emptySet(),
        keyOf: (T) -> String = { "" },
        sameLook: ((T) -> List<String>)? = null,
        artistOf: (T) -> String,
    ): List<T> {
        if (take <= 0 || rows.isEmpty()) return emptyList()
        // Полки должны знать друг о друге. Потолок на артиста действовал
        // ВНУТРИ полки, а между полками не действовал ничего — и на снимке
        // 06.09.2026 «Sour Times» и «Teardrop» стояли в «Из вашей коллекции»
        // и в «Недавно добавленном» одновременно. Две полки, показывающие
        // одно и то же, — это одна полка и одно пустое место.
        //
        // Занятое соседкой не выбрасываем, а отодвигаем в конец очереди: у
        // человека может быть ровно три альбома, и тогда пустая полка хуже
        // повтора. Сначала показываем то, чего ещё не видно нигде.
        //
        // Сверяемся с соседкой ТЕМИ ЖЕ приметами, что и внутри полки. Пока
        // здесь стоял один ключ, а внутри — три, полка честно не повторялась
        // сама, но повторяла соседку: на A31 06.09.2026 «Teardrop» стоял в
        // обеих. Правило должно быть одно, иначе оно ловит только там, где я
        // его в тот раз вспомнил.
        val ordered = if (avoid.isEmpty()) rows else {
            val (seen, fresh) = rows.partition { r ->
                val f = sameLook?.invoke(r)?.map { it.trim().lowercase() }?.filter { it.isNotBlank() }
                if (f.isNullOrEmpty()) keyOf(r) in avoid else f.any { it in avoid }
            }
            fresh + seen
        }
        val used = HashMap<String, Int>()
        val seenLooks = HashSet<String>()    // уже показанное «на вид»
        val picked = ArrayList<T>(take)
        val rest = ArrayList<T>()
        for (r in ordered) {
            if (picked.size >= take) break
            // Дважды одно и то же НА ВИД — второй раз не показываем.
            //
            // Я подходил к этому трижды и трижды считал не то. Сначала
            // ограничил артиста — на A31 06.09.2026 рядом встали два
            // «Teardrop». Ограничил название — рядом встали «Cyberverse» и
            // «Cyberverse (Over Slowed)» с ОДНОЙ И ТОЙ ЖЕ обложкой.
            //
            // Человек не читает поля. Он видит картинку, и две одинаковые
            // картинки подряд для него сломанная полка — чем бы они ни
            // различались в базе. Поэтому ключ здесь — то, как вещь ВЫГЛЯДИТ
            // на карточке, а не то, чем она числится.
            // Совпало ЛЮБОЕ из того, что человек замечает, — это повтор.
            // Обложка и подпись ловят разные случаи: «Cyberverse» и
            // «Cyberverse (Over Slowed)» — одна картинка при разных словах,
            // два «Teardrop» — одно слово при разных картинках. Каждый раз я
            // чинил только одну половину, и вторая тут же вылезала рядом.
            val facets = sameLook?.invoke(r)
                ?.map { it.trim().lowercase() }?.filter { it.isNotBlank() }.orEmpty()
            if (facets.isNotEmpty() && facets.any { it in seenLooks }) {
                rest += r
                continue
            }
            // Занял место — засчитывается КАЖДОМУ, кто указан в строке.
            // Иначе достаточно приписать соавтора, чтобы обойти потолок.
            val names = credited(artistOf(r))
            if (names.none { (used[it] ?: 0) >= maxPerArtist }) {
                names.forEach { used[it] = (used[it] ?: 0) + 1 }
                seenLooks += facets
                picked += r
            } else {
                rest += r
            }
        }
        // Не набрали — добираем отложенным. Полка не должна пустеть только
        // потому, что у человека узкая фонотека.
        if (picked.size < take) picked += rest.take(take - picked.size)
        return picked
    }
}
