package net.ripster.mobile.ui.layout

/**
 * Бюджет хрома оболочки: какая системная рамка показывается при каком окне.
 *
 * Откуда это взялось (E2E-кампания 23.09.2026, продолжение BUG-8): в ландшафте
 * на 2670×1200 неподвижный хром — шапка, полоса «1 готово», мини-плеер и нижняя
 * навигация — съедал ~70% высоты, и на выдачу поиска оставалась одна обрезанная
 * строка. Точечное сжатие шапки (29a9b14) помогло частично: сами горизонтальные
 * полосы — нижняя навигация и статус-строка — в ландшафте не нужны, место для
 * них вертикальное, а в ширину там терять нечего.
 *
 * Правило одно: ширина больше высоты — нижняя навигация уезжает на левый
 * вертикальный рельс, полоса статуса складывается в шапку, мини-плеер
 * становится однострочным. Портрет (ширина ≤ высоты) — ровно то, что было
 * раньше. Арифметика вынесена в чистые функции, чтобы «какой хром в каком
 * классе окна» проверялось тестом, а не скриншотом.
 */
internal object ChromeBudget {

    /** Ширина вертикального рельса навигации (подпись «Библиотека» в одну строку). */
    const val RailWidthDp: Float = 84f

    /** Нижняя навигация: подъём 10 + разделитель + ячейка с иконкой и подписью. */
    const val BottomNavHeightDp: Float = 74f

    /** Полоса статуса загрузок («1 готово») под содержимым. */
    const val StatusStripHeightDp: Float = 26f

    /** Портретный мини-плеер: строка 58 + отступы 8+8 + нить прогресса 2. */
    const val MiniPlayerHeightDp: Float = 76f

    /** Ландшафтный мини-плеер: одна строка 48 + отступы 4+4 + нить прогресса 2. */
    const val CompactMiniPlayerHeightDp: Float = 58f

    /**
     * Класс окна: горизонтальный (ширина больше высоты) — тот самый случай,
     * где вертикальное место дороже горизонтального. Ровно `width > height`,
     * без порога: квадрат — ещё портрет, один пиксель перевеса — уже рельс.
     * Невалидные размеры (окно ещё не развёрнуто, высота ≤ 0) — портрет:
     * выдумывать рельс на нулевой высоте не за что.
     */
    fun useRail(widthDp: Float, heightDp: Float): Boolean =
        heightDp > 0f && widthDp > heightDp

    /** Нижняя навигация остаётся только там, где нет рельса. */
    fun showsBottomNav(widthDp: Float, heightDp: Float): Boolean = !useRail(widthDp, heightDp)

    /** Полоса «N готово» live под контентом в портрете; в ландшафте она складывается в шапку. */
    fun showsStatusStrip(widthDp: Float, heightDp: Float): Boolean = !useRail(widthDp, heightDp)

    /** Однострочный мини-плеер — спутник рельса: оба экономят одну и ту же высоту. */
    fun compactMiniPlayer(widthDp: Float, heightDp: Float): Boolean = useRail(widthDp, heightDp)

    /**
     * Сколько высоты окна уходит на хром кроме шапки и системных панелей.
     * Мини-плеер учтён в обоих классах: он показывается, только когда есть что
     * играть, — это верхняя оценка, и она намеренно консервативна.
     */
    fun chromeHeightDp(widthDp: Float, heightDp: Float): Float =
        if (useRail(widthDp, heightDp)) {
            CompactMiniPlayerHeightDp
        } else {
            StatusStripHeightDp + MiniPlayerHeightDp + BottomNavHeightDp
        }
}
