package net.ripster.mobile.ui.layout

/**
 * Бюджет высоты экрана поиска — кому сколько отдавать, когда места мало.
 *
 * Откуда это взялось (E2E-кампания 23.09.2026, этап 8, BUG-8): ландшафт +
 * открытый мини-плеер. Экран поиска живёт в `Box(Modifier.weight(1f))` стекла
 * `ui/AppShell.kt` и делит высоту с четырьмя НЕсжимаемыми соседями: шапка-бар,
 * полоса загрузок, мини-плеер (≈76dp) и нижняя навигация (≈74dp). В ландшафте
 * на 1200px им доставалось столько, что на выдачу оставалось ~160px, а сама
 * шапка поиска (сервисы + поле + чипы фильтров) съедала ~640px. Итог: список
 * результатов не схлопывался «до одной строки» — его не было вовсе, вместе с
 * пустым состоянием и строкой ошибки, потому что они живут ВНУТРИ списка.
 *
 * `Modifier.weight(1f)` сам по себе тут не лечит: Column отдаёт помеченному
 * weight ребёнку ОСТАТОК от неизрасходованного немаранными детьми, а остаток
 * прижимается к нулю. То есть сначала надо заставить шапку уступить, и только
 * потом список получит хотя бы минимум.
 *
 * Второй вор был тот же самый: жёсткий портретный `contentPadding(bottom =
 * 120.dp)` в ландшафте оказывался БОЛЬШЕ всего списка — прокрутка упиралась в
 * пустую полосу внизу вместо строк.
 *
 * Правила вынесены в чистую арифметику над dp именно из-за порядка: «шапка
 * сжимается ровно на столько, чтобы строка выдачи осталась видимой» — это
 * проверяемое утверждение, а не наблюдение за телефоном.
 */
internal object SearchLayout {

    /** Горизонтальный и вертикальный отступ содержимого `SearchScreen` (padding 16dp). */
    const val ContentPaddingDp: Float = 16f

    /** Низ под выдачу: одна строка результата. Ниже список перестаёт быть списком. */
    const val ResultsMinDp: Float = 64f

    /**
     * Минимальная высота поля запроса (и соседней кнопки «Искать»). Поле —
     * единственная ручка ввода на экране: когда бюджет шапки жмёт, сплющить
     * его нельзя — нельзя и показать экран, где набирать запрос некуда.
     * 56dp — ещё и зона касания не ниже минимума.
     */
    const val FieldMinDp: Float = 56f

    /**
     * Верх для шапки. Нужен только чтобы неограниченный список недавних
     * запросов не вытеснял выдачу на высоком экране.
     *
     * Держим его заведомо выше реальной шапки (сервисы · поле · чипы · недавние
     * запросы), иначе портрет, где места вдоволь, начал бы скроллить шапку
     * вместо того чтобы показать её целиком, как показывает сегодня.
     */
    const val HeaderIdealDp: Float = 320f

    /** Воздух между шапкой и выдачей — и то же место над строкой ошибки. */
    const val GapDp: Float = 12f

    /** Строка ошибки над списком: 13sp текст с запасом на перенос. */
    const val ErrorLineDp: Float = 22f

    /** Портретный низ списка — под плашку исхода, висящую у нижнего края экрана. */
    const val ResultsBottomIdealDp: Float = 120f

    /** Доля доступной высоты экрана, которую нижнему отступу отдавать допустимо. */
    const val ResultsBottomMaxFraction: Float = 0.35f

    /**
     * Доступная высота содержимого экрана по высоте окна [screenDp]: снять
     * верхний и нижний padding.
     */
    fun contentHeightDp(screenDp: Float): Float =
        (screenDp - 2f * ContentPaddingDp).coerceAtLeast(0f)

    /**
     * Максимум, который шапка имеет право занять при доступной высоте
     * [contentDp]. [reservedDp] — то, что стоит между шапкой и выдачей и высоты
     * не уступает ([pinnedAboveResultsDp]).
     *
     * Возвращает ноль, когда не влезает даже минимум под выдачу: тогда шапка
     * сожмётся в ноль и останется скроллиться внутри своей квоты, а человек
     * увидит результат. Шапка без выдачи — это экран, который не показывает
     * то, ради чего на него пришли.
     */
    fun headerMaxHeightDp(contentDp: Float, reservedDp: Float = 0f): Float =
        (contentDp - ResultsMinDp - reservedDp).coerceIn(0f, HeaderIdealDp)

    /** Сколько фиксированного места уйдёт между шапкой и выдачей. */
    fun pinnedAboveResultsDp(errorShown: Boolean): Float =
        GapDp + if (errorShown) ErrorLineDp else 0f

    /**
     * Нижнее пространство списка — чтобы последняя строка доживала до просмотра,
     * а не пряталась под плашкой исхода.
     *
     * Считается от [contentDp] (высота всего содержимого экрана), а не от
     * остатка после шапки: в портрете остаток легко спорит с 120dp и портрет
     * начал бы ездить иначе, чем ездил до BUG-8. В ландшафте же ровно этот
     * жёсткий портретный запас и оказывался БОЛЬШЕ всего списка — прокрутка
     * упиралась в пустую полосу там, где должны быть строки.
     */
    fun resultsBottomPaddingDp(contentDp: Float): Float =
        (contentDp * ResultsBottomMaxFraction)
            .coerceIn(0f, ResultsBottomIdealDp)
}