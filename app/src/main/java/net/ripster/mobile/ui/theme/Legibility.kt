package net.ripster.mobile.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.lerp

/**
 * Читаемость текста поверх того, что реально нарисовано под ним.
 *
 * `PaletteContrastTest` меряет контраст токенов палитры по ПОВЕРХНОСТЯМ палитры,
 * и до 23.09.2026 этого хватало — пока не оказалось, что плееры рисуют собственный
 * фон: «Studio» и «Immersive» закрашивают экран near-black с цветным градиентом из
 * обложки, а подписи рисуют `Color.White.copy(alpha = 0.5f)` и токенами палитры
 * поверх. Тест этого не видит: он не знает, что под текстом лежит НЕ surface_*.
 * Отсюда снимок владельца: «0:52 / 5:41 почти не видно» — в светлой палитре
 * `text_secondary` это ТЁМНО-серый, а под ним почти чёрный фон плеера.
 *
 * Поэтому: всякий раз, когда текст ложится на заведомо чужую поверхность (фон
 * плеера, обложка, стекло с прозрачностью), цвет нужно пропускать через
 * [legibleOn] — он снимает альфу относительно фона и добирает контраст, только
 * если его и правда не хватает.
 */

/** Основной текст: WCAG AA для обычного кегля. */
const val MinTextContrast: Float = 4.5f

/**
 * Второстепенный и «приглушённый» текст — строки лирики вдали от текущей,
 * подписи времени. Порог ниже, но НЕ 3:1 «как для крупного»: строка песни
 * набрана мелким кеглем, и довод «это же декорация» не проходит — человек
 * читает именно её.
 */
const val MinDimmedContrast: Float = 3.2f

/** Приведение цвета с альфой к тому, что реально видно над [bg]. */
fun blendOver(fg: Color, bg: Color): Color =
    if (fg.alpha >= 0.999f) fg else lerp(bg, fg, fg.alpha)

/**
 * Тот же цвет, но гарантированно читаемый над [bg].
 *
 * Альфа снимается (полупрозрачный серый над белым — это НЕ серый, а «светлый»,
 * и контраст мерить надо по результату), и если результата не хватает — цвет
 * добирается к противоположной полярности минимальным шагом. Обычный случай
 * (текст и так контрастен) возвращается без изменения, так что дизайн не
 * «улучшается» насильно.
 *
 * Результат всегда непрозрачен: рисовать его надо как есть, иначе композитор
 * смешает его с тем же фоном второй раз и порог уже не сойдётся.
 */
fun legibleOn(fg: Color, bg: Color, min: Float = MinTextContrast): Color {
    // Плоский цвет берётся непрозрачным: иначе вызывающий нарисует его над тем
    // же фоном второй раз и обещанный контраст рассыплется (БАГ-8).
    val flat = blendOver(fg, bg).copy(alpha = 1f)
    if (contrastRatio(flat, bg) >= min) return flat
    // Полярность — та, чей контраст с фоном БОЛЬШЕ, а не «белый, если L<0.5»:
    // точка равного запаса вверх и вниз лежит на L ≈ 0.179 (её же выводит
    // CoverTint), и в зазоре 0.179…0.5 белый уже не дотягивает до AA, а чёрный
    // дотягивает.
    val ink = if (contrastRatio(Color.White, bg) >= contrastRatio(Color.Black, bg)) Color.White else Color.Black
    var lo = 0f
    var hi = 1f
    // Инваринт: lerp(flat, ink, hi) обязан проходить порог. Если не проходит и
    // чистый `ink` (кислотный фон), лучше которого ничего нет — отдаём его.
    if (contrastRatio(lerp(flat, ink, 1f), bg) < min) return ink
    repeat(8) {
        val mid = (lo + hi) / 2f
        if (contrastRatio(lerp(flat, ink, mid), bg) >= min) hi = mid else lo = mid
    }
    return lerp(flat, ink, hi)
}

/**
 * Приглушение с полом: «тише, но всё ещё читается».
 *
 * `[dim]` — насколько увести цвет в фон (1f = растворить). Раньше в лирике для
 * этого писали `.copy(alpha = 0.10f)`, и строка песни исчезала на фоне градиента:
 * альфа — это НЕ «насколько тише», это «насколько видно то, что под текстом».
 */
fun dimOn(fg: Color, bg: Color, dim: Float, min: Float = MinDimmedContrast): Color =
    legibleOn(lerp(fg, bg, dim.coerceIn(0f, 1f)), bg, min)
