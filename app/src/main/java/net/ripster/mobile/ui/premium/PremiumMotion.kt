package net.ripster.mobile.ui.premium

import kotlin.math.abs

/**
 * Числа пружинного движения «дорогих визуалов» — отдельно от того, где оно
 * рисуется.
 *
 * Причина вынести в чистый слой та же, что у [PremiumVisuals.resolve]: на приборе
 * не проверить, КАК ИМЕННО выглядит отказ от эффекта, а угадывать нельзя. Здесь
 * нет ни Context, ни Compose — только вход (что разрешил план + что происходит
 * с треком) и выход (конкретный масштаб, радиус, фокус). Компоновщик только
 * берёт посчитанное.
 */
object PremiumMotion {

    /** Масштаб обложки, когда музыка играет: свой размер. */
    const val ARTWORK_PLAYING: Float = 1f

    /**
     * Масштаб на паузе. Чуть меньше единицы — обложка «садится», как пластинка,
     * которую остановили. Заметимо глазом, но не карикатура: при 0.9 и ниже
     * обложка в мини-плеере и в полном расходятся слишком сильно и переход
     * начинает читаться как прыжок.
     */
    const val ARTWORK_PAUSED: Float = 0.955f

    /**
     * Обложка в такт play/pause. Когда пружины запрещены (режим выключен,
     * системная «без анимации» или экономия заряда) масштаб всегда 1f: сжатие без
     * пружинного доводчика читается не как «обложка дышит», а как дёрганье.
     */
    fun artworkScale(springMotion: Boolean, isPlaying: Boolean): Float =
        if (!springMotion || isPlaying) ARTWORK_PLAYING else ARTWORK_PAUSED

    /**
     * Перетекает ли обложка из мини-плеера в полный. Одного разрешения на пружину
     * мало: нужен ещё и замеренный прямоугольник обложки в плашке, иначе лететь
     * не откуда — и тогда переход остаётся таким, каким был до режима.
     */
    fun coverEnter(springMotion: Boolean, miniCoverBoundsKnown: Boolean): Boolean =
        springMotion && miniCoverBoundsKnown
}

/**
 * Форма стеклянного органа под пальцем.
 *
 * Стекло не «темнеет» от нажатия и не бледнеет — оно продавливается: вниз по
 * вертикали до [PRESS_SQUISH], с небольшим перелётом по горизонтали (материал
 * никуда не девается, он расходится в стороны) и с тем же перелётом при
 * возврате. Именно перелёт отличает «жидкое» стекло от «плитки, севшей на
 * таймере»: доводчик тут пружина, а не `tween`.
 *
 * Когда пружины запрещены (режим выключен, «убрать анимацию» в системе или
 * экономия заряда) — `null`: рисующий не применяет никакой трансформации, и
 * нажатие выглядит ровно как до режима. Водить масштаб без пружинного
 * доводчика — значит получить дёрганье вместо стекла.
 */
data class PressShape(val scaleX: Float, val scaleY: Float)

object PressSpring {

    /** До чего продавливается орган под пальцем. */
    const val PRESS_SQUISH: Float = 0.92f

    /** Насколько он расширяется по второй оси: стекло сохраняет «объём». */
    const val PRESS_STRETCH: Float = 1.045f

    /** Возврат из-под пальца: орган чуть перелетает через свой размер. */
    const val RELEASE_OVERSHOOT: Float = 1.03f

    /**
     * Масштабы по осям. `pressed` — палец внутри; `settle` — только что
     * отпущенный орган в момент перелёта (его рисует пружина, но величину
     * задаём здесь, чтобы её было чем проверить).
     */
    fun shapeFor(pressed: Boolean, springsOn: Boolean, settle: Boolean = false): PressShape? = when {
        !springsOn -> null
        pressed -> PressShape(scaleX = PRESS_STRETCH, scaleY = PRESS_SQUISH)
        settle -> PressShape(scaleX = RELEASE_OVERSHOOT, scaleY = RELEASE_OVERSHOOT)
        else -> PressShape(1f, 1f)
    }
}

/**
 * Состояние одной строки синхронного текста.
 *
 * Что строка собой представляет (звучит / уже спета / ждёт своей очереди),
 * насколько она приглушена и нужно ли её размывать — решает [LyricsLineState],
 * а не место в разметке: те же правила читают и караоке по словам (Apple), и
 * построчный LRCLIB, иначе два текста на одном экране выглядели бы по-разному.
 */
data class LyricLine(
    /** Эта строка звучит сейчас. */
    val active: Boolean,
    /** 1f — звучит; меньше — чем дальше от звучащей. Идёт в альфу и в вес. */
    val focus: Float,
    /** Радиус размытия в dp. `0f` — не размывать (текущая строка всегда резкая). */
    val blurDp: Float,
    /** Растить ли шрифт. Только у звучащей строки — см. [LyricsLineState.lineAt]. */
    val grow: Boolean,
)

object LyricsLineState {

    /** Насколько глуше становится каждая следующая ушедшая/предстоящая строка. */
    private const val PAST_STEP = 0.06f
    private const val PAST_FLOOR = 0.10f
    private const val NEXT_STEP = 0.07f
    private const val NEXT_FLOOR = 0.16f

    /** Прирост размытия на одну строку от центра, dp. */
    const val BLUR_PER_LINE: Float = 1.6f

    /** Дальше трёх строк размывать сильнее бессмысленно — их всё равно не читают. */
    const val BLUR_MAX_LINES: Int = 3

    /**
     * Индекс строки, которая звучит при позиции [positionMs].
     *
     * До первой строки ещё не дошло — подсвечиваем первую (текст стоит на ней, а
     * не «в никуда»); между строками держим предыдущую, иначе в паузе между
     * словами строка мигала бы на следующую раньше времени.
     *
     * Перебор, а не бинарный поиск: тайминги приходят из стороннего сервиса
     * (LRCLIB, Apple через ПК-мост), иsorted-гарантии у них нет. На паре
     * десятков строк это ничего не стоит, а на кривых данных поиск молча
     * подсвечивает не ту строку.
     */
    fun activeIndex(startsMs: List<Long>, positionMs: Long): Int {
        val i = startsMs.indexOfLast { it <= positionMs }
        return if (i < 0) 0 else i
    }

    /**
     * Фокус строки по расстоянию до звучащей: 0 — она сама.
     *
     * Спета (выше) — глуше, чем предстоящая (ниже): человек уже понял, что в
     * этой строке, а следующую читает вперёд, её и держим читаемой. Границы
     * те же, что были в разметке до этой правки — режим не должен тихонько
     * обесцветить текст, который и так был виден.
     */
    fun focus(distance: Int): Float = when {
        distance == 0 -> 1f
        distance < 0 -> (0.40f - PAST_STEP * -distance).coerceIn(PAST_FLOOR, 0.40f)
        else -> (0.60f - NEXT_STEP * distance).coerceIn(NEXT_FLOOR, 0.60f)
    }

    /**
     * Всё, что нужно рисовальщику строки. [depthEnabled] — вердикт плана
     * ([PremiumPlan.lyricsDepth]): на Android младше 12 и в экономии заряда
     * размытия нет, но фокус по строкам остаётся — приглушение дешёвое.
     *
     * Шрифт растит ТОЛЬКО звучащая строка. Если бы размер зависел от расстояния,
     * смена строки меняла бы высоту всех видимых строк сразу — текст начинал бы
     * подпрыгивать на каждом слове.
     */
    fun lineAt(index: Int, activeIndex: Int, depthEnabled: Boolean): LyricLine {
        val d = index - activeIndex
        val f = focus(d)
        return LyricLine(
            active = d == 0,
            focus = f,
            blurDp = if (!depthEnabled || d == 0) 0f
                else (BLUR_PER_LINE * abs(d).coerceAtMost(BLUR_MAX_LINES)),
            grow = d == 0,
        )
    }
}
